const K = require('../lib/kernl');
const { buildEpub, renderCover } = require('../lib/epub');

// First publication year from Open Library (the same free service the app uses for new-book suggestions).
// Only trusted when the author matches; anything slow, missing or implausible means no year on the cover.
async function lookupYear(title, author) {
  const ctl = new AbortController();
  const timer = setTimeout(() => ctl.abort(), 3000);
  try {
    const url = 'https://openlibrary.org/search.json?title=' + encodeURIComponent(title) + (author ? '&author=' + encodeURIComponent(author) : '') + '&limit=5&fields=title,author_name,first_publish_year';
    const r = await fetch(url, { signal: ctl.signal, headers: { 'User-Agent': 'KERNL (kernlbooks.com)' } });
    if (!r.ok) return null;
    const d = await r.json();
    const now = new Date().getFullYear();
    for (const doc of (d && d.docs) || []) {
      const y = Number(doc.first_publish_year);
      if (!(y >= 1450 && y <= now)) continue;
      const names = doc.author_name || [];
      if (author && !names.some(n => K.authorMatches(n, author))) continue;
      return y;
    }
    return null;
  } catch (e) {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

function safe(s) {
  return String(s).replace(/[^a-z0-9]/gi,'_').replace(/_+/g,'_').slice(0,60);
}

module.exports = async (req, res) => {
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  // Only Amazon's own Send-to-Kindle addresses. Without this the endpoint is an open email relay.
  const body = req.body || {};
  const kindleEmail = String(body.kindleEmail || '').trim().toLowerCase();
  if (!/^[a-z0-9._%+\-]{1,64}@(free\.)?kindle\.com$/.test(kindleEmail)) {
    return res.status(400).json({ error: 'Please enter your Kindle address (it ends in @kindle.com).' });
  }
  const reqTitle = K.cleanText(body.title, 300), reqAuthor = K.cleanText(body.author, 300);
  if (!reqTitle) return res.status(400).json({ error: 'Title is required' });

  const RESEND_API_KEY = process.env.RESEND_API_KEY;
  if (!RESEND_API_KEY) return res.status(500).json({ error: 'Resend not configured' });

  const ctx = await K.authenticate(req);
  if (ctx && ctx.tier === 'guest') return res.status(403).json({ code: 'signup_required', error: 'Create a free account to send summaries to your Kindle.' });
  const who = ctx && ctx.user ? ctx.user.id : K.clientIp(req);
  if (!(ctx && ctx.admin) && K.rateLimited('kindle:' + who, 10, 60 * 60 * 1000)) {
    return res.status(429).json({ error: 'Too many sends. Try again later.' });
  }

  // The content comes from the library, never from the request body.
  const book = await K.findBook(reqTitle, reqAuthor);
  if (!book || !book.html) return res.status(404).json({ error: 'Summary not found' });
  const access = await K.authoriseAudioRead(ctx, book); // guest book, or one in the user's library
  if (!access.ok) return K.fail(res, access);
  const title = book.title, author = book.author || '', html = book.html;

  try {
    // Build EPUB: valid XHTML, full metadata, and a cover image carrying the title and author
    const year = await lookupYear(title, author);
    const cover = renderCover(title, author, year);
    const epubBuffer = await buildEpub({ title, author, html, cover });
    const filename = safe(title) + '_KERNL.epub';
    const epubBase64 = epubBuffer.toString('base64');

    // Send via Resend
    const emailRes = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${RESEND_API_KEY}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        from: 'KERNL <kindle@kernlbooks.com>',
        to: [kindleEmail],
        subject: title + ' — KERNL Summary',
        text: `Your KERNL summary of "${title}" by ${author} is attached as an EPUB file. Open it on your Kindle to start reading.\n\nGenerated by KERNL — for the curious\nkernlbooks.com`,
        attachments: [
          {
            filename: filename,
            content: epubBase64,
            content_type: 'application/epub+zip'
          }
        ]
      })
    });

    const emailData = await emailRes.json();
    if (!emailRes.ok) {
      console.error('Resend error:', emailData);
      return res.status(500).json({ error: emailData.message || 'Email failed to send' });
    }

    return res.status(200).json({ ok: true, id: emailData.id });

  } catch (err) {
    console.error('Send to Kindle error:', err.message);
    return res.status(500).json({ error: err.message || 'Failed to send to Kindle' });
  }
};
